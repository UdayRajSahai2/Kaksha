/**
 * Kaksha against Skyfield (spec CORE-07). Reference states come from
 * notebooks/skyfield_crosscheck.py; see the fixture README for what each field is.
 *
 * Tolerances, fixed before the first run:
 * - TEME at the same minutes since epoch: two SGP4 implementations of the same algorithm and
 *   constants: 1 mm, 0.1 mm/s (as for the verification vectors). The same UTC instant is
 *   reported only: there each side's float epoch adds sub-microsecond time differences.
 * - Earth-fixed: Skyfield's TEME vector through both transforms, so only the transform differs.
 * - Earth-fixed with UTC as UT1: Skyfield's TEME_to_ITRF is the same GMST-1982 model, so
 *   1 mm in position. Velocity 1 mm/s, stated when Kaksha used the WGS-84 nominal Earth rate
 *   (7.292115e-5 rad/s) against Skyfield's GMST-1982 rate; the first run measured 1.9 mm/s at
 *   220 000 km, and temeToEcef now uses the GMST-1982 rate (gmstRateRadPerS).
 * - Full chain (IAU 2000/2006, real UT1): Kaksha ignores UT1 - UTC, so first rotate Kaksha's
 *   position by the Earth rotation over UT1 - UTC; what remains is the difference between the
 *   TEME-GMST1982 route and the full precession-nutation route, allowed 50 m.
 */
import { describe, expect, it } from 'vitest';
import reference from './__fixtures__/skyfield/skyfield-reference.json' with { type: 'json' };
import { ecefToGeodetic, temeToEcef } from './frames.ts';
import { propagateTeme, propagateTemeAtMinutes, satelliteFromTle } from './sgp4.ts';
import { utcMs } from './time.ts';
import { minutes, radToDeg } from './units.ts';
import { magnitude, subtract, type Vec3, vec3 } from './vectors.ts';

const TEME_KM = 1e-6;
const TEME_KM_S = 1e-7;
const PEF_KM = 1e-6;
const PEF_KM_S = 1e-6;
const FULL_CHAIN_KM = 0.05;
/** Earth rotation angle rate per UT1 second (GMST-1982 rate). */
const ROTATION_RAD_PER_S = 7.292_115_855_3e-5;
const MEAN_EARTH_RADIUS_KM = 6371;

type Point = (typeof reference.points)[number];
const v = <F extends 'teme' | 'ecef', U extends 'km' | 'km/s'>(a: number[]) =>
  vec3<F, U>(a[0] ?? Number.NaN, a[1] ?? Number.NaN, a[2] ?? Number.NaN);

function rotateZ(p: Vec3<'ecef', 'km'>, angle: number): Vec3<'ecef', 'km'> {
  const c = Math.cos(angle);
  const s = Math.sin(angle);
  return vec3(c * p.x + s * p.y, -s * p.x + c * p.y, p.z);
}

const wrapDeg = (d: number) => ((((d + 180) % 360) + 360) % 360) - 180;

function compare(p: Point) {
  const sat = satelliteFromTle(p.line1, p.line2);
  const t = utcMs(p.tUtcMs);
  const byMinutes = propagateTemeAtMinutes(sat, minutes(p.minutesSinceEpoch));
  const s = propagateTeme(sat, t);
  if (!s.ok || !byMinutes.ok) throw new Error(`${p.satnum} at ${p.minutesSinceEpoch} min: SGP4 failed`);
  // The transform alone: Skyfield's TEME vector through Kaksha's temeToEcef.
  const refPef = temeToEcef(v<'teme', 'km'>(p.temeKm), v<'teme', 'km/s'>(p.temeKmS), t);
  // End to end: what Kaksha shows for this UTC instant.
  const ecef = temeToEcef(s.state.posTemeKm, s.state.velTemeKmS, t);
  const rotation = ROTATION_RAD_PER_S * p.ut1MinusUtcS;
  const corrected = rotateZ(ecef.posEcefKm, rotation);
  const g = ecefToGeodetic(ecef.posEcefKm);
  const radiusXy = Math.hypot(ecef.posEcefKm.x, ecef.posEcefKm.y);
  return {
    satnum: p.satnum,
    temeKm: magnitude(subtract(byMinutes.state.posTemeKm, v<'teme', 'km'>(p.temeKm))),
    temeKmS: magnitude(subtract(byMinutes.state.velTemeKmS, v<'teme', 'km/s'>(p.temeKmS))),
    instantKm: magnitude(subtract(s.state.posTemeKm, v<'teme', 'km'>(p.temeAtInstantKm))),
    pefKm: magnitude(subtract(refPef.posEcefKm, v<'ecef', 'km'>(p.pefUtcKm))),
    pefKmS: magnitude(subtract(refPef.velEcefKmS, v<'ecef', 'km/s'>(p.pefUtcKmS))),
    fullChainRawKm: magnitude(subtract(ecef.posEcefKm, v<'ecef', 'km'>(p.itrsKm))),
    ut1RotationKm: Math.abs(rotation) * radiusXy,
    fullChainKm: magnitude(subtract(corrected, v<'ecef', 'km'>(p.itrsKm))),
    latKm: (Math.abs(radToDeg(g.latRad) - p.latDeg) * Math.PI * MEAN_EARTH_RADIUS_KM) / 180,
    heightKm: Math.abs(g.altKm - p.heightKm),
    lonResidualKm:
      (Math.abs(wrapDeg(radToDeg(g.lonRad) - radToDeg(rotation as never) - p.lonDeg)) * Math.PI * radiusXy) /
      180,
  };
}

const results = reference.points.map(compare);
type Key = Exclude<keyof (typeof results)[number], 'satnum'>;
const max = (k: Key) => Math.max(...results.map((r) => r[k]));
const rms = (k: Key) => Math.sqrt(results.reduce((sum, r) => sum + r[k] ** 2, 0) / results.length);
const sig = (x: number) => (x === 0 ? '0' : x.toPrecision(2));
const row = (label: string, k: Key, unit: 'm' | 'mm' | 'mm/s', tolerance: string) => {
  const scale = unit === 'm' ? 1e3 : 1e6;
  return `| ${label} | ${sig(max(k) * scale)} ${unit} | ${sig(rms(k) * scale)} ${unit} | ${tolerance} |`;
};

function report(): string {
  return [
    '# Kaksha against Skyfield',
    '',
    'Generated by `packages/astro/src/skyfield.crosscheck.test.ts` from `notebooks/skyfield_crosscheck.py`; do not edit by hand. CI fails if the results change.',
    '',
    `Reference: Skyfield ${reference.meta.skyfield} with python-sgp4 ${reference.meta.sgp4}, ${reference.meta.timescale}, polar motion ${reference.meta.polarMotion}. ${results.length} points: the first, middle and last reference step of each SGP4 verification case (Vallado et al. 2006).`,
    '',
    '| Comparison | Max | RMS | Tolerance |',
    '| --- | --- | --- | --- |',
    row('TEME position at the same minutes since epoch (python-sgp4)', 'temeKm', 'mm', '1 mm'),
    row('TEME velocity at the same minutes since epoch', 'temeKmS', 'mm/s', '0.1 mm/s'),
    row('TEME position at the same UTC instant (Skyfield)', 'instantKm', 'mm', 'reported'),
    row(
      'Earth-fixed position of the same TEME vector, same model (GMST 1982, UTC as UT1)',
      'pefKm',
      'mm',
      '1 mm',
    ),
    row('Earth-fixed velocity of the same TEME vector, same model', 'pefKmS', 'mm/s', '1 mm/s'),
    row(
      'Earth-fixed position against the full IAU 2000/2006 chain, as computed',
      'fullChainRawKm',
      'm',
      'reported',
    ),
    row('Of which Earth rotation over UT1 - UTC (Kaksha uses UTC)', 'ut1RotationKm', 'm', 'reported'),
    row('Full chain after removing the UT1 - UTC rotation', 'fullChainKm', 'm', '50 m'),
    row('Geodetic latitude (as ground distance)', 'latKm', 'm', '50 m'),
    row('Geodetic height', 'heightKm', 'm', '50 m'),
    row('Geodetic longitude after removing the UT1 - UTC rotation', 'lonResidualKm', 'm', '50 m'),
    '',
    "Reading it: rows 1, 2, 4 and 5 check the code against independent implementations of the same models. Row 3 adds each side’s conversion from a UTC instant to minutes since epoch; its millimetres are sub-microsecond differences in how each side holds the epoch as a float (float64 resolves 0.12 microseconds at 1e12 ms). The full-chain rows measure what Kaksha's documented approximations cost: almost all of the raw difference is Earth rotation over UT1 - UTC, which Kaksha ignores (see `docs/known-limits.md`); the rest is the difference between the TEME-GMST 1982 route and the modern precession-nutation route.",
    '',
  ].join('\n');
}

describe('Kaksha against Skyfield', () => {
  it('compares every reference point', () => {
    expect(results.length).toBeGreaterThan(90);
  });

  it.each(results.map((r, i) => ({ ...r, i })))('point $i (NORAD $satnum) is within tolerance', (r) => {
    expect(r.temeKm).toBeLessThanOrEqual(TEME_KM);
    expect(r.temeKmS).toBeLessThanOrEqual(TEME_KM_S);
    expect(r.pefKm).toBeLessThanOrEqual(PEF_KM);
    expect(r.pefKmS).toBeLessThanOrEqual(PEF_KM_S);
    expect(r.fullChainKm).toBeLessThanOrEqual(FULL_CHAIN_KM);
    expect(r.latKm).toBeLessThanOrEqual(FULL_CHAIN_KM);
    expect(r.heightKm).toBeLessThanOrEqual(FULL_CHAIN_KM);
    expect(r.lonResidualKm).toBeLessThanOrEqual(FULL_CHAIN_KM);
  });

  it('matches the committed results table', async () => {
    await expect(report()).toMatchFileSnapshot('../../../docs/validation/skyfield-crosscheck.md');
  });
});
