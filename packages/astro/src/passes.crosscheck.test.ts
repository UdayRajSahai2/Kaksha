/**
 * Pass prediction against Skyfield's find_events (spec PASS-04). Reference from
 * notebooks/skyfield_crosscheck.py: four LEO verification cases over three stations, one day
 * each, 10 deg mask, geometric elevation.
 *
 * Tolerances, fixed before the first run: rise and set 2 s (Kaksha rotates the Earth by UTC,
 * Skyfield by UT1, which moves the ground track by up to about 0.4 km, well under a second of
 * horizon crossing); culmination time 5 s (the peak is flat, so its time is poorly conditioned);
 * peak elevation 0.05 deg. Every Skyfield pass must have a Kaksha pass and the other way round.
 */
import { describe, expect, it } from 'vitest';
import reference from './__fixtures__/skyfield/skyfield-passes.json' with { type: 'json' };
import { predictPasses } from './passes.ts';
import { satelliteFromTle } from './sgp4.ts';
import { utcMs } from './time.ts';
import { station } from './topocentric.ts';
import { deg, degToRad, km, radToDeg } from './units.ts';

const RISE_SET_S = 2;
const CULMINATION_S = 5;
const PEAK_DEG = 0.05;

type Window = (typeof reference.windows)[number];

function compare(w: Window) {
  const sat = satelliteFromTle(w.line1, w.line2);
  const site = station({
    latRad: degToRad(deg(w.latDeg)),
    lonRad: degToRad(deg(w.lonDeg)),
    altKm: km(w.heightKm),
  });
  const ours = predictPasses(sat, site, utcMs(w.fromUtcMs), utcMs(w.toUtcMs), {
    minElevation: deg(reference.maskDeg),
  });
  const nearest = (times: number[], t: number) => Math.min(...times.map((x) => Math.abs(x - t) / 1000));
  const of = (kind: string) => w.events.filter((e) => e.kind === kind);
  const rises = ours.filter((p) => !p.clippedByWindow || p.rise.t > w.fromUtcMs).map((p) => Number(p.rise.t));
  const sets = ours.filter((p) => !p.clippedByWindow || p.set.t < w.toUtcMs).map((p) => Number(p.set.t));
  const riseErr = of('rise').map((e) => nearest(rises, e.tUtcMs));
  const setErr = of('set').map((e) => nearest(sets, e.tUtcMs));
  const culmErr = of('culmination').map((e) => {
    const match = ours.reduce((best, p) =>
      Math.abs(p.culmination.t - e.tUtcMs) < Math.abs(best.culmination.t - e.tUtcMs) ? p : best,
    );
    return {
      timeS: Math.abs(match.culmination.t - e.tUtcMs) / 1000,
      peakDeg: Math.abs(radToDeg(match.culmination.elevationRad) - e.elevationDeg),
    };
  });
  return {
    label: `${w.satnum} over ${w.station}`,
    skyfieldRises: of('rise').length,
    kakshaRises: rises.length,
    passes: ours.length,
    maxRiseS: Math.max(0, ...riseErr),
    maxSetS: Math.max(0, ...setErr),
    maxCulmS: Math.max(0, ...culmErr.map((c) => c.timeS)),
    maxPeakDeg: Math.max(0, ...culmErr.map((c) => c.peakDeg)),
  };
}

const results = reference.windows.map(compare);
const sig = (x: number) => (x === 0 ? '0' : x.toPrecision(2));

function report(): string {
  const all = (k: 'maxRiseS' | 'maxSetS' | 'maxCulmS' | 'maxPeakDeg') =>
    Math.max(...results.map((r) => r[k]));
  return [
    '# Pass prediction against Skyfield',
    '',
    'Generated by `packages/astro/src/passes.crosscheck.test.ts` from `notebooks/skyfield_crosscheck.py`; do not edit by hand. CI fails if the results change.',
    '',
    `Skyfield \`find_events\`, ${reference.maskDeg} deg mask, geometric elevation, one day from each element epoch. ${results.length} satellite and station pairs, ${results.reduce((n, r) => n + r.passes, 0)} passes.`,
    '',
    '| Measure | Worst case | Tolerance |',
    '| --- | --- | --- |',
    `| Rise time | ${sig(all('maxRiseS'))} s | ${RISE_SET_S} s |`,
    `| Set time | ${sig(all('maxSetS'))} s | ${RISE_SET_S} s |`,
    `| Culmination time | ${sig(all('maxCulmS'))} s | ${CULMINATION_S} s |`,
    `| Peak elevation | ${sig(all('maxPeakDeg'))} deg | ${PEAK_DEG} deg |`,
    '',
    'Every Skyfield pass has a Kaksha pass and the other way round. Most of the time difference is Earth rotation over UT1 - UTC, which Kaksha ignores.',
    '',
    '| Pair | Passes | Worst rise (s) | Worst set (s) | Worst culmination (s) | Worst peak (deg) |',
    '| --- | --- | --- | --- | --- | --- |',
    ...results.map(
      (r) =>
        `| ${r.label} | ${r.passes} | ${sig(r.maxRiseS)} | ${sig(r.maxSetS)} | ${sig(r.maxCulmS)} | ${sig(r.maxPeakDeg)} |`,
    ),
    '',
  ].join('\n');
}

describe('pass prediction against Skyfield', () => {
  it.each(results)('$label', (r) => {
    expect(r.kakshaRises).toBe(r.skyfieldRises);
    expect(r.maxRiseS).toBeLessThanOrEqual(RISE_SET_S);
    expect(r.maxSetS).toBeLessThanOrEqual(RISE_SET_S);
    expect(r.maxCulmS).toBeLessThanOrEqual(CULMINATION_S);
    expect(r.maxPeakDeg).toBeLessThanOrEqual(PEAK_DEG);
  });

  it('matches the committed results table', async () => {
    await expect(report()).toMatchFileSnapshot('../../../docs/validation/passes-crosscheck.md');
  });
});
