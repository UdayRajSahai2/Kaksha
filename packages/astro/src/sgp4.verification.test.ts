/**
 * SGP4 against the published verification vectors (spec CORE-06), via the shared runner
 * in verification.ts. Also writes the committed results table; CI fails if it drifts.
 */
import { describe, expect, it } from 'vitest';
import tleText from './__fixtures__/sgp4-verification/SGP4-VER.TLE?raw';
import expectedText from './__fixtures__/sgp4-verification/tcppver.out?raw';
import {
  parseVerificationCases,
  parseVerificationReference,
  runSgp4Verification,
  VERIFICATION_POSITION_TOLERANCE_KM,
  VERIFICATION_VELOCITY_TOLERANCE_KM_S,
  type VerificationSummary,
} from './verification.ts';

const sig = (value: number) => (value === 0 ? '0' : value.toPrecision(2));

function report(s: VerificationSummary): string {
  const rows = s.cases.map(
    (r) =>
      `| ${r.satnum} | ${r.startMin} to ${r.stopMin} | ${r.points} | ${sig(r.maxPosErrKm * 1e6)} | ${sig(r.maxVelErrKmS * 1e6)} | ${r.ending} |`,
  );
  return [
    '# SGP4 verification results',
    '',
    'Generated by `packages/astro/src/sgp4.verification.test.ts`; do not edit by hand. CI fails if the results change.',
    '',
    'Kaksha\'s SGP4 wrapper (satellite.js 7.1.0, WGS-72, improved mode) against the verification vectors of Vallado et al., "Revisiting Spacetrack Report #3", AIAA 2006-6753. Errors are the distance between TEME vectors.',
    '',
    `Tolerance: position ${sig(VERIFICATION_POSITION_TOLERANCE_KM * 1e6)} mm, velocity ${sig(VERIFICATION_VELOCITY_TOLERANCE_KM_S * 1e6)} mm/s (100 times the reference's printed precision).`,
    '',
    '| Summary | Value |',
    '| --- | --- |',
    `| Cases | ${s.cases.length} |`,
    `| Points compared | ${s.points} |`,
    `| Max position error | ${sig(s.maxPosErrKm * 1e6)} mm |`,
    `| RMS position error | ${sig(s.rmsPosErrKm * 1e6)} mm |`,
    `| Max velocity error | ${sig(s.maxVelErrKmS * 1e6)} mm/s |`,
    '',
    'This measures the implementation, not the model. SGP4 with real element sets is accurate to about a kilometre at epoch; see `docs/known-limits.md`.',
    '',
    '"Ending" checks the step after the reference output stops: the reference lists only steps that propagated, so a case that stops early must report an SGP4 error there.',
    '',
    '| NORAD | Span (min) | Points | Max position error (mm) | Max velocity error (mm/s) | Ending |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}

describe('SGP4 verification vectors (Vallado et al. 2006)', () => {
  const summary = runSgp4Verification(tleText, expectedText);

  it('runs all 33 cases', () => {
    expect(summary.cases).toHaveLength(33);
  });

  it('rejects 33334 at load; its single reference row is stale output from the previous case', () => {
    // SGP4 initialisation propagates to t = 0 and fails (error 3). Vallado's C++ driver then
    // printed the r, v left over from case 33333, so that row is not a state of 33334.
    const cases = parseVerificationCases(tleText);
    const blocks = parseVerificationReference(expectedText);
    const index = cases.findIndex((c) => c.satnum === 33334);
    const previousLast = blocks[index - 1]?.rows.at(-1);
    expect(blocks[index]?.rows).toEqual([{ ...previousLast, minutes: 0 }]);
    expect(summary.cases[index]?.ending).toBe('rejected when loaded: perturbed-eccentricity-out-of-range');
  });

  it.each(summary.cases)('NORAD $satnum ($startMin to $stopMin min) is within tolerance', (r) => {
    expect(r.maxPosErrKm).toBeLessThanOrEqual(VERIFICATION_POSITION_TOLERANCE_KM);
    expect(r.maxVelErrKmS).toBeLessThanOrEqual(VERIFICATION_VELOCITY_TOLERANCE_KM_S);
    expect(r.withinTolerance).toBe(true);
  });

  it('matches the committed error table', async () => {
    await expect(report(summary)).toMatchFileSnapshot('../../../docs/validation/sgp4-verification.md');
  });
});
